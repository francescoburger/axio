#!/usr/bin/env python3
"""Deterministic flash assets; checked-in header also works in Arduino IDE."""
from pathlib import Path
import gzip
ROOT=Path(__file__).resolve().parents[1]
WEB=ROOT/'firmware/Axio/web'
OUT=ROOT/'firmware/Axio/src/web/WebAssets.h'
parts=['// Generated by scripts/package_web.py; edit firmware/Axio/web sources.\n#pragma once\n#include <stddef.h>\nnamespace axio { namespace web {\n']
for name,symbol in [('index.html','index'),('style.css','style'),('app.js','app')]:
    data=gzip.compress((WEB/name).read_bytes(),compresslevel=9,mtime=0)
    parts.append('static const unsigned char '+symbol+'[]={\n')
    parts.extend(','.join(str(b) for b in data[i:i+24])+',\n' for i in range(0,len(data),24))
    parts.append('};\n')
parts.append('}}\n')
text=''.join(parts)
if not OUT.exists() or OUT.read_text()!=text:OUT.write_text(text)
print('PASS: embedded web assets current')
